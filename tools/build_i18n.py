"""Build static/i18n-en.js, the English interface text that every page loads first.

static/i18n/en.json stays the single English source. The generated script lets the page,
the Mini Player owner and the frontend tests read English synchronously, without a request,
and gives every translation a complete fallback. Run after editing en.json or manifest.json;
`--check` fails when the generated file is out of date.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STATIC = ROOT / "src" / "tagcast" / "static"
TARGET = STATIC / "i18n-en.js"


def build(static=STATIC):
    manifest = json.loads((static / "i18n" / "manifest.json").read_text(encoding="utf-8"))
    messages = json.loads((static / "i18n" / "en.json").read_text(encoding="utf-8"))
    if not isinstance(messages, dict) or not all(isinstance(v, str) for v in messages.values()):
        raise ValueError("en.json must map keys to plain strings")
    data = json.dumps({"manifest": manifest, "messages": dict(sorted(messages.items()))},
                      ensure_ascii=False, indent=1)
    return ('"use strict";\n'
            "// Generated by tools/build_i18n.py from i18n/manifest.json and i18n/en.json. Do not edit.\n"
            f"globalThis.TagcastI18nEnglish = Object.freeze({data});\n")


def main(argv):
    output = build()
    if argv[1:] == ["--check"]:
        if TARGET.read_text(encoding="utf-8") != output:
            print("i18n-en.js is out of date. Run python3 tools/build_i18n.py", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(output, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
